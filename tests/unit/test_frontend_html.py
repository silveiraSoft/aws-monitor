class TestFrontendSecurity(unittest.TestCase):
    """Tests for security best practices in the frontend."""

    @classmethod
    def setUpClass(cls):
        with open(TS_FILE, encoding="utf-8") as f:
            cls.html = extract_html(f.read())

    def test_no_inline_event_xss_risk(self):
        """All onclick handlers only call internal functions, not eval."""
        onclick_vals = re.findall(r'onclick="([^"]+)"', self.html)
        for val in onclick_vals:
            self.assertNotIn("eval(", val)
            self.assertNotIn("document.write", val)

    def test_no_hardcoded_aws_account(self):
        """Account ID in the UI info text is acceptable but no secrets."""
        self.assertNotRegex(self.html, r'AKIA[A-Z0-9]{16}')

    def test_no_hardcoded_secret_key(self):
        """No AWS secret key pattern."""
        self.assertNotRegex(self.html, r'[A-Za-z0-9/+=]{40}')

    def test_xss_prevention_in_user_bubbles(self):
        """User messages use escapeHtml, not innerHTML directly."""
        js_start = self.html.find("<script>")
        js = self.html[js_start:]
        # escapeHtml is called for user role
        self.assertIn("escapeHtml(text)", js)

    def test_api_url_relative_to_deployment(self):
        """API URL is injected via CDK, not hardcoded."""
        self.assertIn("${apiUrl}", self.html)
        self.assertNotRegex(self.html, r'https://[a-z0-9]+\.execute-api\.')


class TestFrontendAccessibility(unittest.TestCase):
    """Tests for basic accessibility requirements."""

    @classmethod
    def setUpClass(cls):
        with open(TS_FILE, encoding="utf-8") as f:
            cls.html = extract_html(f.read())

    def test_lang_attribute_on_html(self):
        self.assertIn('lang="en"', self.html)

    def test_title_element_present(self):
        self.assertIn("<title>", self.html)

    def test_button_has_title_attribute(self):
        send_btn = re.search(r'<button[^>]*id="send"[^>]*>', self.html)
        self.assertIsNotNone(send_btn)
        self.assertIn("title=", send_btn.group(0))

    def test_textarea_has_placeholder(self):
        self.assertIn("placeholder=", self.html)

    def test_contrast_dark_theme(self):
        """Text color should be near-white on dark background."""
        text_match = re.search(r'--text:\s*(#[0-9a-fA-F]+)', self.html)
        self.assertIsNotNone(text_match)
        hex_val = text_match.group(1).lstrip('#')
        r = int(hex_val[0:2], 16)
        self.assertGreater(r, 180, f"Text color not bright enough for dark bg: #{hex_val}")

    def test_focus_styles_present(self):
        """Input must have visible focus indicator."""
        self.assertIn(":focus", self.html)

    def test_font_size_readable(self):
        """Base font size should be ≥13px."""
        sizes = re.findall(r'font-size:\s*(\d+(?:\.\d+)?)px', self.html)
        base_sizes = [float(s) for s in sizes]
        self.assertTrue(
            any(s >= 13 for s in base_sizes),
            f"No font-size ≥ 13px found. Sizes: {base_sizes}"
        )


