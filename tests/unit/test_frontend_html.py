class TestFrontendDesignTokens(unittest.TestCase):
    """Tests for modern CSS design system (custom properties, dark theme)."""

    @classmethod
    def setUpClass(cls):
        with open(TS_FILE, encoding="utf-8") as f:
            cls.html = extract_html(f.read())
        # Extract :root block
        m = re.search(r':root\s*\{([^}]+)\}', cls.html, re.DOTALL)
        cls.root_vars = m.group(1) if m else ""

    def _css_vars(self):
        return re.findall(r'(--[\w-]+):', self.root_vars)

    def test_minimum_css_variables(self):
        """Must define at least 15 CSS custom properties."""
        self.assertGreaterEqual(len(self._css_vars()), 15)

    def test_color_palette_defined(self):
        for var in ("--bg", "--surface", "--border", "--accent", "--text"):
            self.assertIn(var, self.root_vars, f"Missing CSS var: {var}")

    def test_dark_background(self):
        """Background color must be a dark hex (starts with #0 or #1)."""
        bg_match = re.search(r'--bg:\s*(#[0-9a-fA-F]+)', self.root_vars)
        self.assertIsNotNone(bg_match, "--bg color not found")
        bg_hex = bg_match.group(1)
        self.assertRegex(bg_hex, r'^#[01]', f"Background not dark enough: {bg_hex}")

    def test_aws_orange_accent(self):
        """Accent color should use AWS orange (#ff9900)."""
        self.assertIn("#ff9900", self.html.lower())

    def test_semantic_color_vars(self):
        """Must define green, red, yellow for status indicators."""
        for var in ("--green", "--red", "--yellow"):
            self.assertIn(var, self.root_vars)

    def test_border_radius_defined(self):
        self.assertIn("--radius", self.root_vars)

    def test_transition_var(self):
        self.assertIn("--transition", self.root_vars)

    def test_font_stack_defined(self):
        self.assertIn("--font", self.root_vars)
        self.assertIn("--mono", self.root_vars)

    def test_animations_defined(self):
        animations = re.findall(r'@keyframes\s+(\w+)', self.html)
        self.assertGreaterEqual(len(animations), 3,
                                f"Expected ≥3 animations, found: {animations}")
        self.assertIn("fadeIn", animations)
        self.assertIn("bounce", animations)


