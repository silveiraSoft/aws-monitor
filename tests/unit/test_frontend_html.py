class TestFrontendJavaScript(unittest.TestCase):
    """Tests for JavaScript logic and API integration."""

    @classmethod
    def setUpClass(cls):
        with open(TS_FILE, encoding="utf-8") as f:
            cls.html = extract_html(f.read())

    def _js_section(self):
        start = self.html.find("<script>")
        end   = self.html.find("</script>") if "</script>" in self.html \
                else self.html.find(r"<\/script>")
